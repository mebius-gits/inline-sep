import { chromium } from 'playwright';
import { mkdir, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import { createApp } from '../app.js';

await mkdir('artifacts', {recursive:true});
const dir=await mkdtemp(join(tmpdir(),'inline-sep-browser-'));
const {app,db}=await createApp({dbPath:join(dir,'browser.sqlite'),adminPassword:'browser-test-password-123'});
const server=app.listen(0,'127.0.0.1'); await new Promise(resolve=>server.once('listening',resolve));
const base=`http://127.0.0.1:${server.address().port}`;
let browser;
const errors=[];
const track=page=>{page.on('pageerror',error=>errors.push(error.message));page.on('console',msg=>{if(msg.type()==='error') errors.push(msg.text());});};
try {
  browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL||'chrome',headless:true});
  const desktop=await browser.newPage({viewport:{width:1440,height:1000}}); track(desktop);
  await desktop.goto(base); await desktop.locator('.meal-card').last().waitFor();
  assert.equal(await desktop.locator('.meal-card').count(),39);
  await desktop.screenshot({path:'artifacts/desktop.png',fullPage:true});
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true}); track(mobile);
  await mobile.goto(base); await mobile.locator('.meal-card').last().waitFor();
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await mobile.screenshot({path:'artifacts/mobile.png',fullPage:true});
  await mobile.locator('.meal-card [data-add="127962"]').click();
  await mobile.locator('.meal-card [data-add="127962"]').click();
  assert.equal(await mobile.locator('.meal-card [data-add="127963"]').isDisabled(),true);
  await mobile.locator('#open-cart').click();
  await mobile.locator('#student-id').fill('B11200001');
  await mobile.locator('#order-note').fill('小辣、不加蒜');
  await mobile.screenshot({path:'artifacts/mobile-checkout.png'});
  await mobile.locator('#submit-order').click();
  await mobile.locator('#receipt-dialog[open]').waitFor();
  assert.match(await mobile.locator('#receipt-content').innerText(),/B11200001/);
  assert.match(await mobile.locator('#receipt-content').innerText(),/NT\$150/);
  await mobile.locator('#close-receipt').click();
  const admin=await browser.newPage({viewport:{width:1440,height:1000}}); track(admin);
  await admin.goto(base+'/admin'); await admin.locator('#admin-password').fill('browser-test-password-123');
  await admin.locator('#login-submit').click(); await admin.locator('#stat-count').filter({hasText:'1'}).waitFor();
  assert.match(await admin.locator('#orders-content').innerText(),/B11200001/);
  await admin.screenshot({path:'artifacts/admin.png',fullPage:true});
  await admin.locator('[data-tab="notes"]').click();
  assert.match(await admin.locator('#split-notes').inputValue(),/學號 B11200001：鹽酥雞 × 2/);
  await admin.screenshot({path:'artifacts/admin-notes.png',fullPage:true});
  const downloadEvent=admin.waitForEvent('download'); await admin.locator('#download-notes').click(); const download=await downloadEvent; assert.match(download.suggestedFilename(),/split-notes/);
  await admin.locator('[data-tab="orders"]').click(); await admin.locator('#toggle-round').click(); await admin.locator('#confirm-action').click();
  await admin.locator('#admin-round-status').filter({hasText:'已截止收單'}).waitFor();
  await mobile.reload(); await mobile.locator('#round-status').filter({hasText:'已截止收單'}).waitFor();
  assert.equal(await mobile.locator('.meal-card [data-add="127962"]').isDisabled(),true);
  await admin.locator('#toggle-round').click(); await admin.locator('#confirm-action').click(); await admin.locator('#admin-round-status').filter({hasText:'開放登記中'}).waitFor();
  await admin.locator('#new-round').click(); await admin.locator('#new-round-name').fill('週五班級團購'); await admin.locator('#new-round-form button[type="submit"]').click();
  await admin.locator('#stat-count').filter({hasText:'0'}).waitFor();
  await admin.locator('#round-select').selectOption('1'); await admin.locator('#stat-count').filter({hasText:'1'}).waitFor();
  await admin.locator('[data-tab="menu"]').click(); await admin.locator('[data-meal="127962"] [data-field="price"]').fill('80'); await admin.locator('[data-save-meal="127962"]').click();
  await admin.locator('#toast').filter({hasText:'已儲存'}).waitFor();
  await desktop.reload(); await desktop.locator('.meal-card[data-id="127962"] .meal-price').filter({hasText:'NT$80'}).waitFor();
  await admin.setViewportSize({width:390,height:844}); await admin.locator('[data-tab="orders"]').click();
  assert.equal(await admin.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await admin.screenshot({path:'artifacts/admin-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Browser checks passed: desktop, mobile, NT$150 limit, submission, receipt, admin login, notes download, close/reopen, history, menu edit, responsive overflow, no browser errors.');
} finally { await browser?.close(); await new Promise(resolve=>server.close(resolve)); db.close(); await rm(dir,{recursive:true,force:true}); }
